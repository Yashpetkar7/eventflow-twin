"""Derive scheduled trains per hour per corridor station and direction from the official RTA GTFS feed.

Input : data/raw/gtfs_official_2021/*.zip (RTA GTFS, service 2021-09-09..2021-12-31, via Mobility Database mdb-904)
Output: config/capacity_gtfs.yaml  (small derived table, committed; provenance included)

Platforms: each metro station has two GTFS stops, "<Name> Metro Station 1" and "... 2" (one per direction).
Hours >= 24 (after-midnight trips of the same service day) are folded into hour 0. Day types are the 2021
calendar's service patterns; mapping to post-2022 weekdays lives in corridor.yaml (capacity.gtfs_daytype_for_weekday).

    python scripts/gtfs_capacity.py
"""
from __future__ import annotations

import datetime as dt
import hashlib
import sys
import zipfile
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from apps.api.eventflow.config import corridor  # noqa: E402

RAW = ROOT / "data/raw/gtfs_official_2021"
OUT = ROOT / "config/capacity_gtfs.yaml"
DAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]


def main() -> Path:
    zips = sorted(RAW.glob("*.zip"))
    if not zips:
        raise SystemExit(f"No GTFS zip in {RAW}. See data/raw/MANIFEST.md.")
    zpath = zips[-1]
    z = zipfile.ZipFile(zpath)
    read = lambda n, **k: pd.read_csv(z.open(n), dtype=str, **k)  # noqa: E731

    routes, trips, cal, stops = read("routes.txt"), read("trips.txt"), read("calendar.txt"), read("stops.txt")
    stations = corridor()["stations"]
    line_route = {}
    for line in {s["line"] for s in stations}:
        m = routes[(routes.route_type == "1") & (routes.route_short_name.str.lower() == f"m{line.lower()}")]
        if len(m) != 1:
            raise SystemExit(f"Expected one metro route for line {line}, found {len(m)}")
        line_route[line] = m.route_id.iloc[0]

    stop_ids: dict[str, list[str]] = {}
    coords: dict[str, tuple[float, float]] = {}
    for s in stations:
        ids = [str(i) for i in s.get("gtfs_stop_ids", [])]
        rows = stops[stops.stop_id.isin(ids)]
        if len(rows) != 2:
            raise SystemExit(f"{s['id']}: expected 2 platform stops {ids}, found {len(rows)}")
        stop_ids[s["id"]] = ids
        coords[s["id"]] = (round(float(rows.stop_lat.astype(float).mean()), 6), round(float(rows.stop_lon.astype(float).mean()), 6))

    sid_to_station = {sid: st for st, ids in stop_ids.items() for sid in ids}
    line_trips = trips[trips.route_id.isin(line_route.values())][["trip_id", "service_id", "direction_id"]]
    keep = set(line_trips.trip_id)
    parts = [ch[ch.stop_id.isin(sid_to_station) & ch.trip_id.isin(keep)] for ch in
             pd.read_csv(z.open("stop_times.txt"), dtype=str, usecols=["trip_id", "stop_id", "departure_time"],
                         chunksize=1_000_000)]
    st = pd.concat(parts).merge(line_trips, on="trip_id")
    st["hour"] = st.departure_time.str.split(":").str[0].astype(int) % 24
    st["station"] = st.stop_id.map(sid_to_station)
    c = cal.set_index("service_id")
    st["daytype"] = st.service_id.map(lambda s: "+".join(d[:3] for d in DAYS if c.loc[s, d] == "1"))

    tph: dict = {}
    for (daytype, station, direction), g in st.groupby(["daytype", "station", "direction_id"]):
        counts = g.groupby("hour").size()
        tph.setdefault(daytype, {}).setdefault(station, {})[f"dir{direction}"] = [int(counts.get(h, 0)) for h in range(24)]

    out = {
        "_provenance": {
            "source": "RTA GTFS schedule feed (official), via Mobility Database mdb-904",
            "url": "https://files.mobilitydatabase.org/mdb-904/mdb-904-202406071531/mdb-904-202406071531.zip",
            "file": zpath.name,
            "sha256": hashlib.sha256(zpath.read_bytes()).hexdigest(),
            "service_period": f"{cal.start_date.min()}..{cal.end_date.max()}",
            "generated": dt.date.today().isoformat(),
            "notes": "Scheduled departures per clock hour at each corridor platform; hours >= 24 folded into 0. "
                     "2021 calendar = Fri–Sat weekend; see corridor.yaml capacity.gtfs_daytype_for_weekday.",
            "licence": "Dubai Pulse / RTA open data terms; credit RTA open data",
        },
        "station_coords": {k: list(v) for k, v in coords.items()},
        "trains_per_hour": tph,
    }
    OUT.write_text("# GENERATED by scripts/gtfs_capacity.py — do not edit by hand\n"
                   + yaml.safe_dump(out, sort_keys=False, width=200), encoding="utf-8")
    print(f"wrote {OUT} ({len(tph)} day types × {len(stop_ids)} stations × 2 directions)")
    return OUT


if __name__ == "__main__":
    main()
