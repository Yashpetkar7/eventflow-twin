"""Station demand levels from the real ridership check → config/calibration.yaml.

Reads the newest eval/results/ridership_check_*.json (written by scripts/ingest.py from the open Dubai Metro
ridership sample, scaled with the official monthly check-ins per station) and writes, per corridor station, the
ratio of real weekday entries per day to the synthetic panel's. The forecast applies these ratios when a request
asks for `demand_level: "real_totals"` (forecast.py). Only the LEVEL is real: the hourly shape stays synthetic,
because the open data has no time of day for these dates (docs/14).
Usage: python scripts/build_calibration.py
"""
from __future__ import annotations

import glob
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    files = sorted(glob.glob(str(ROOT / "eval/results/ridership_check_*.json")))
    if not files:
        raise SystemExit("no eval/results/ridership_check_*.json — run the ingest check first (docs/14)")
    src = Path(files[-1])
    d = json.loads(src.read_text(encoding="utf-8"))
    m = d["metrics"]
    out = {"source": f"eval/results/{src.name}", "window": m["window"], "scale_method": m["scale_method"],
           "note": "real weekday entries per day ÷ synthetic weekday entries per day; level only, hourly shape stays synthetic",
           "stations": {s: {"ratio": v["real_over_synthetic"], "real_weekday_entries": v["weekday_entries_per_day_scaled"],
                            "synthetic_weekday_entries": v["synthetic_weekday_entries_per_day"]}
                        for s, v in m["corridor_stations"].items()}}
    p = ROOT / "config/calibration.yaml"
    p.write_text("# Generated by scripts/build_calibration.py — do not edit by hand.\n" + yaml.safe_dump(out, sort_keys=False, allow_unicode=True),
                 encoding="utf-8")
    print(f"wrote {p.relative_to(ROOT)} from {src.name}: " + ", ".join(f"{s} ×{v['ratio']}" for s, v in out["stations"].items()))


if __name__ == "__main__":
    main()
